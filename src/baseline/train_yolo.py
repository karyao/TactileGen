"""Train (or fine-tune) the chart detector on a balanced, reproducible subset.

    python -m src.baseline.train_yolo --data-root dataset_yolo_bars_clean \
        --weights models/yolo_vbars/best.pt --per-type 10000 --val-per-type 1000 \
        --epochs 15 --output runs/bars_hv

``--data-root`` is a cleaned dataset from ``prepare_plotqa.py`` and
``remove_split_leakage.py``: ``images/``, ``labels/``, ``classes.txt`` and
``chart_types_<split>.csv`` for train and val. The subset is drawn at random
with ``--seed`` from the **train** and **val** splits only, the same number of
charts per chart type; the test split is never read here. Every setting, the
subset sizes and the image lists are saved in the output folder so a run can
be repeated exactly.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
from collections import Counter
from pathlib import Path

DEFAULT_CHART_TYPES = ("vbar_categorical", "hbar_categorical")


def read_chart_types(data_root: Path, split: str) -> dict[str, str]:
    """``image_id -> chart_type`` from ``chart_types_<split>.csv``."""
    manifest = data_root / f"chart_types_{split}.csv"
    if not manifest.is_file():
        raise FileNotFoundError(f"Missing chart-type manifest: {manifest}")
    with manifest.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["image_id", "chart_type"]:
            raise ValueError(f"Invalid chart-type manifest: {manifest}")
        return {row["image_id"]: row["chart_type"] for row in reader}


def select_subset(chart_types: dict[str, str], wanted: tuple[str, ...],
                  per_type: int | None, seed: int) -> list[str]:
    """Up to ``per_type`` image IDs of each wanted chart type, chosen at random.

    The choice depends only on the IDs, ``per_type`` and ``seed``, so the same
    inputs always give the same subset. ``per_type=None`` keeps every image.
    """
    if per_type is not None and per_type < 1:
        raise ValueError("per-type count must be positive")
    rng = random.Random(seed)
    chosen: list[str] = []
    for chart_type in wanted:
        ids = sorted((i for i, t in chart_types.items() if t == chart_type), key=int)
        if not ids:
            raise ValueError(f"No {chart_type} images in the manifest")
        if per_type is not None and per_type < len(ids):
            ids = sorted(rng.sample(ids, per_type), key=int)
        chosen.extend(ids)
    return chosen


def write_image_list(data_root: Path, split: str, ids: list[str], path: Path) -> Path:
    """An Ultralytics image-list file; labels are found via images/ -> labels/."""
    images = data_root.resolve() / "images" / split
    missing = [i for i in ids if not (images / f"{i}.png").is_file()]
    if missing:
        raise FileNotFoundError(f"{len(missing)} listed {split} images are missing, e.g. {missing[0]}")
    path.write_text("".join(f"{(images / f'{i}.png').as_posix()}\n" for i in ids), encoding="utf-8")
    return path


def write_data_yaml(output: Path, data_root: Path, train_list: Path, val_list: Path) -> Path:
    names = (data_root / "classes.txt").read_text(encoding="utf-8").splitlines()
    path = output / "data.yaml"
    path.write_text(
        "# Generated by src.baseline.train_yolo; train/val are subset lists.\n"
        f"train: {train_list.resolve().as_posix()}\n"
        f"val: {val_list.resolve().as_posix()}\n"
        f"test: {(data_root.resolve() / 'images' / 'test').as_posix()}\n"
        f"nc: {len(names)}\n"
        "names:\n" + "".join(f"  {k}: {name}\n" for k, name in enumerate(names)),
        encoding="utf-8")
    return path


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def prepare_run(data_root: Path, output: Path, chart_types: tuple[str, ...],
                per_type: int | None, val_per_type: int | None, seed: int) -> dict:
    """Write the subset lists and data.yaml; return what was chosen."""
    output.mkdir(parents=True, exist_ok=True)
    summary = {}
    lists = {}
    for split, count in (("train", per_type), ("val", val_per_type)):
        types = read_chart_types(data_root, split)
        ids = select_subset(types, chart_types, count, seed)
        lists[split] = write_image_list(data_root, split, ids, output / f"{split}_images.txt")
        summary[split] = dict(Counter(types[i] for i in ids))
    data_yaml = write_data_yaml(output, data_root, lists["train"], lists["val"])
    return {"data_yaml": str(data_yaml), "counts": summary}


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="run folder")
    parser.add_argument("--weights", type=Path, required=True,
                        help="starting checkpoint, e.g. models/yolo_vbars/best.pt to fine-tune")
    parser.add_argument("--chart-types", nargs="+", default=list(DEFAULT_CHART_TYPES))
    parser.add_argument("--per-type", type=int, help="train charts per type (default: all)")
    parser.add_argument("--val-per-type", type=int, help="val charts per type (default: all)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--epochs", type=int, default=15)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--mosaic", type=float, default=0.0,
                        help="0 matches the best ablation checkpoint (best_no_mosaic)")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--device", help="Ultralytics device, e.g. 0 or cpu")
    parser.add_argument("--prepare-only", action="store_true",
                        help="write the subset lists and data.yaml, then stop")
    args = parser.parse_args(argv)

    run = prepare_run(args.data_root, args.output, tuple(args.chart_types),
                      args.per_type, args.val_per_type, args.seed)
    config = {
        "data_root": str(args.data_root), "weights": str(args.weights),
        "weights_sha256": _sha256(args.weights), "chart_types": args.chart_types,
        "per_type": args.per_type, "val_per_type": args.val_per_type, "seed": args.seed,
        "epochs": args.epochs, "imgsz": args.imgsz, "batch": args.batch,
        "mosaic": args.mosaic, **run,
    }
    print(json.dumps(config["counts"], indent=2))
    if args.prepare_only:
        (args.output / "run_config.json").write_text(json.dumps(config, indent=2) + "\n",
                                                     encoding="utf-8")
        return

    from ultralytics import YOLO, __version__ as ultralytics_version
    config["ultralytics"] = ultralytics_version
    (args.output / "run_config.json").write_text(json.dumps(config, indent=2) + "\n",
                                                 encoding="utf-8")
    model = YOLO(str(args.weights))
    model.train(
        data=run["data_yaml"], epochs=args.epochs, imgsz=args.imgsz, batch=args.batch,
        seed=args.seed, deterministic=True, mosaic=args.mosaic,
        close_mosaic=0 if args.mosaic == 0 else 10, workers=args.workers,
        device=args.device, project=str(args.output.resolve()), name="train", exist_ok=True,
    )
    print(f"Best checkpoint: {args.output / 'train' / 'weights' / 'best.pt'}")


if __name__ == "__main__":
    main()
